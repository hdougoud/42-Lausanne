#include <unistd.h>

void	ft_print_comb(void);

void	ft_write_numbers(int i, int j, int k)
{
	write(1, &i, 1);
	write(1, &j, 1);
	write(1, &k, 1);
}

void	ft_print_comb(void)
{
	int	i;
	int	j;
	int	k;

	i = '0';
	while (i <= '7')
	{
		j = i + 1;
		while (j <= '8')
		{
			k = j + 1;
			while (k <= '9')
			{
				ft_write_numbers(i, j, k);
				if (i != '7')
				{
					write(1, ",", 1);
					write(1, " ", 1);
				}
				k ++;
			}
			j ++;
		}
		i ++;
	}
}
