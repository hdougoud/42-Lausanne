#include "get_next_line.h"

char *get_next_line(int fd)
{
	t_line *new;
	static char buff[BUFFER_SIZE];
	
	new = malloc(sizeof(t_line));
	if (!new)
		return (NULL);
	read(fd, buff, BUFFER_SIZE);
	new->content = buff;
	new->next = NULL;
	return (new->content);
}

